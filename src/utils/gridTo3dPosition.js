// Коэффициенты масштаба под ваш скан (если чуть сдвинуто — подкрутите на 0.01)
const STEP_LONG = 0.965; // шаг вдоль длинной стороны (23 узла -> на экране слева направо)
const STEP_SHORT = 0.965; // шаг вдоль короткой стороны (13 узлов -> на экране сверху вниз)

const OFFSET_LONG = 0.0; // сдвиг всей сетки влево/вправо на экране
const OFFSET_SHORT = 0.0; // сдвиг всей сетки вверх/вниз на экране

export function nodeToWorld(x, y, altitude = 0.1) {
  // x (0..22) — слева направо на экране -> мировая ось Z (знак минус, чтобы 0 был слева)
  // y (0..12) — сверху вниз на экране -> мировая ось X (так как камера стоит в +X = 0.1)
  const worldX = (y - 6) * STEP_SHORT + OFFSET_SHORT;
  const worldZ = -(x - 11) * STEP_LONG + OFFSET_LONG;

  return [worldX, altitude, worldZ];
}

export function dirToRotation(dir) {
  // При таком ракурсе камеры:
  // dir = 1 (вправо по экрану, в сторону -Z) -> поворот 0
  // dir = 3 (влево по экрану, в сторону +Z) -> поворот Math.PI
  // dir = 0 (вверх по экрану, в сторону -X) -> поворот Math.PI / 2
  // dir = 2 (вниз по экрану, в сторону +X) -> поворот -Math.PI / 2
  const angles = [
    Math.PI / 2, // 0: Вверх
    0, // 1: Вправо
    -Math.PI / 2, // 2: Вниз
    Math.PI, // 3: Влево
  ];
  return angles[dir] || 0;
}
